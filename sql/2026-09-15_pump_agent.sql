-- สั่งจ่าย — คืน ticket_ref ให้ PWA เอาไปเฝ้าดูผลผ่าน Realtime
-- ⚠️ ห้ามเรียกผ่าน offline outbox: ถ้าคิวไว้แล้ว flush ทีหลัง
--    หัวจ่ายจะปลดล็อกตอนไม่มีใครอยู่ ฝั่งแอปต้องปิดปุ่มเมื่อออฟไลน์
CREATE OR REPLACE FUNCTION request_pump_command(
  p_nozzle_code text, p_kind text, p_payload jsonb DEFAULT '{}'::jsonb,
  p_ttl_seconds integer DEFAULT 60)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_nozzle bigint; v_ticket uuid; v_live fuel_nozzle_live%ROWTYPE; v_agent timestamptz;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'ต้องล็อกอินก่อน'; END IF;
  IF current_staff_role() NOT IN ('CASHIER','OWNER') THEN
    RAISE EXCEPTION 'สิทธิ์ไม่พอ: เฉพาะพนักงานขายหรือเจ้าของร้าน';
  END IF;
  IF p_kind = 'SET_PRICE' AND current_staff_role() <> 'OWNER' THEN
    RAISE EXCEPTION 'เปลี่ยนราคาได้เฉพาะเจ้าของร้าน';
  END IF;

  SELECT id INTO v_nozzle FROM fuel_nozzles WHERE code = p_nozzle_code AND active;
  IF v_nozzle IS NULL THEN RAISE EXCEPTION 'ไม่รู้จักหัวจ่าย %', p_nozzle_code; END IF;

  -- ตัวแทนต้องยังมีชีวิต ไม่งั้นคำสั่งจะค้างอยู่เฉย ๆ
  SELECT max(last_seen_at) INTO v_agent FROM pump_agents;
  IF v_agent IS NULL OR v_agent < now() - interval '2 minutes' THEN
    RAISE EXCEPTION 'ตัวแทนหัวจ่ายออฟไลน์ สั่งจ่ายไม่ได้';
  END IF;

  SELECT * INTO v_live FROM fuel_nozzle_live WHERE nozzle_id = v_nozzle;
  IF p_kind LIKE 'AUTHORIZE%' THEN
    IF v_live.nozzle_id IS NULL OR NOT v_live.online THEN
      RAISE EXCEPTION 'หัวจ่าย % ขาดการติดต่อ', p_nozzle_code;
    END IF;
    IF v_live.state IN ('AUTHORIZED','FILLING') THEN
      RAISE EXCEPTION 'หัวจ่าย % กำลังจ่ายอยู่', p_nozzle_code;
    END IF;
  END IF;

  INSERT INTO pump_commands (nozzle_id, kind, payload, requested_by, expires_at)
  VALUES (v_nozzle, p_kind, p_payload, current_staff_name(),
          now() + make_interval(secs => GREATEST(10, LEAST(300, p_ttl_seconds))))
  RETURNING ticket_ref INTO v_ticket;
  RETURN v_ticket;
EXCEPTION WHEN unique_violation THEN
  RAISE EXCEPTION 'หัวจ่าย % มีคำสั่งค้างอยู่ รอให้เสร็จก่อน', p_nozzle_code;
END; $$;

-- ผูกรายการที่จ่ายจริงเข้ากับบิลขาย (เก็บเงินตามยอดจริง ไม่ใช่ยอด preset)
CREATE OR REPLACE FUNCTION settle_pump_transaction(p_ticket_ref uuid, p_sales_order_id bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'ต้องล็อกอินก่อน'; END IF;
  IF current_staff_role() NOT IN ('CASHIER','OWNER') THEN RAISE EXCEPTION 'สิทธิ์ไม่พอ'; END IF;
  UPDATE fuel_pump_transactions
     SET sales_order_id = p_sales_order_id, status = 'PAID'
   WHERE ticket_ref = p_ticket_ref AND status = 'UNPAID';
  IF NOT FOUND THEN RAISE EXCEPTION 'ไม่พบรายการที่ยังไม่ชำระสำหรับ ticket นี้'; END IF;
END; $$;

DO $$
DECLARE f text;
BEGIN
  FOREACH f IN ARRAY ARRAY[
    'pump_agent_heartbeat(text,text,jsonb,jsonb)','claim_pump_commands(text)',
    'finish_pump_command(bigint,text,text)','push_nozzle_live(jsonb)',
    'push_totalizer_snapshots(jsonb)','push_pump_transactions(jsonb)',
    'request_pump_command(text,text,jsonb,integer)','settle_pump_transaction(uuid,bigint)'] LOOP
    EXECUTE format('REVOKE EXECUTE ON FUNCTION %s FROM PUBLIC, anon', f);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO authenticated', f);
  END LOOP;
END $$;

-- ==========================================================================
-- สะพานเข้ากับรายงานเดิม
-- pivot totalizer ปลายวันกลับเป็นรูปตารางกว้างแบบ fuel_meter_readings
-- -> รายงานและ RPC เดิมทำงานต่อได้โดยไม่ต้องแก้ แล้วค่อยย้ายทีละหน้า
--
-- หมายเหตุ: คอลัมน์ *_small (มิเตอร์กลไก) อ่านผ่าน RS-485 ไม่ได้
--           ยังต้องกรอกมือ และมันมีค่า — เป็นตัวตรวจสอบไขว้กับมิเตอร์ดิจิทัล
-- ==========================================================================
CREATE OR REPLACE VIEW fuel_meter_readings_auto AS
WITH eod AS (
  SELECT DISTINCT ON (n.code, (s.taken_at AT TIME ZONE 'Asia/Bangkok')::date)
         n.code,
         (s.taken_at AT TIME ZONE 'Asia/Bangkok')::date AS reading_date,
         s.vol_total, s.amt_total
    FROM fuel_totalizer_snapshots s
    JOIN fuel_nozzles n ON n.id = s.nozzle_id
   ORDER BY n.code, 2, s.taken_at DESC
)
SELECT reading_date,
       MAX(vol_total) FILTER (WHERE code = 'diesel_west_front') AS diesel_west_front_digital,
       MAX(amt_total) FILTER (WHERE code = 'diesel_west_front') AS diesel_west_front_digital_money,
       MAX(vol_total) FILTER (WHERE code = 'diesel_west_back')  AS diesel_west_back_digital,
       MAX(amt_total) FILTER (WHERE code = 'diesel_west_back')  AS diesel_west_back_digital_money,
       MAX(vol_total) FILTER (WHERE code = 'diesel_east_front') AS diesel_east_front_digital,
       MAX(amt_total) FILTER (WHERE code = 'diesel_east_front') AS diesel_east_front_digital_money,
       MAX(vol_total) FILTER (WHERE code = 'diesel_east_back')  AS diesel_east_back_digital,
       MAX(amt_total) FILTER (WHERE code = 'diesel_east_back')  AS diesel_east_back_digital_money,
       MAX(vol_total) FILTER (WHERE code = 'gas91_front')       AS gas91_front_digital,
       MAX(amt_total) FILTER (WHERE code = 'gas91_front')       AS gas91_front_digital_money,
       MAX(vol_total) FILTER (WHERE code = 'gas91_back')        AS gas91_back_digital,
       MAX(amt_total) FILTER (WHERE code = 'gas91_back')        AS gas91_back_digital_money,
       MAX(vol_total) FILTER (WHERE code = 'gas95_front')       AS gas95_front_digital,
       MAX(amt_total) FILTER (WHERE code = 'gas95_front')       AS gas95_front_digital_money,
       MAX(vol_total) FILTER (WHERE code = 'gas95_back')        AS gas95_back_digital,
       MAX(amt_total) FILTER (WHERE code = 'gas95_back')        AS gas95_back_digital_money
  FROM eod GROUP BY reading_date;

GRANT SELECT ON fuel_meter_readings_auto TO authenticated;

