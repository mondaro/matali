-- ---------------------------------------------------------------- ทะเบียนหัวจ่าย
-- ผูกโลกจริง (บัส/บอร์ด/หัวจ่าย) เข้ากับชื่อคอลัมน์เดิมใน fuel_meter_readings
CREATE TABLE IF NOT EXISTS fuel_nozzles (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             text NOT NULL UNIQUE,      -- 'diesel_west_front' = prefix คอลัมน์เดิม
  label            text NOT NULL,             -- 'ดีเซล ฝั่งตะวันตก หน้า'
  fuel_type        text NOT NULL,
  bus_id           text NOT NULL DEFAULT 'bus1',
  board_addr       smallint NOT NULL,
  nozzle_no        smallint NOT NULL,
  pulses_per_litre integer NOT NULL DEFAULT 100,
  sort_order       smallint NOT NULL DEFAULT 0,
  active           boolean NOT NULL DEFAULT true,
  created_at       timestamptz NOT NULL DEFAULT now(),
  UNIQUE (bus_id, board_addr, nozzle_no)
);

-- ---------------------------------------------------------------- สถานะสด
-- 1 แถวต่อหัวจ่าย UPDATE ทับที่เดิม — PWA ฟังผ่าน Supabase Realtime
-- ห้ามทำเป็นตาราง append ไม่งั้นจะได้แสนแถวต่อวันโดยไม่มีประโยชน์
CREATE TABLE IF NOT EXISTS fuel_nozzle_live (
  nozzle_id   bigint PRIMARY KEY REFERENCES fuel_nozzles(id) ON DELETE CASCADE,
  state       text NOT NULL DEFAULT 'UNKNOWN'
    CHECK (state IN ('UNKNOWN','IDLE','NOZZLE_UP','AUTHORIZED','FILLING','DONE')),
  online      boolean NOT NULL DEFAULT false,
  liters      numeric NOT NULL DEFAULT 0,
  amount      numeric NOT NULL DEFAULT 0,
  unit_price  numeric NOT NULL DEFAULT 0,
  ticket_ref  uuid,                            -- ผูกกับคำสั่งที่ PWA ส่งมา
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- totalizer
-- ยอดสะสมจากมิเตอร์อิเล็กทรอนิกส์ = ความจริงสูงสุดของการกระทบยอด
CREATE TABLE IF NOT EXISTS fuel_totalizer_snapshots (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_ref text UNIQUE NOT NULL,             -- idiom เดิมของระบบ กัน insert ซ้ำ
  nozzle_id  bigint NOT NULL REFERENCES fuel_nozzles(id),
  taken_at   timestamptz NOT NULL DEFAULT now(),
  vol_total  numeric NOT NULL,
  amt_total  numeric,
  source     text NOT NULL DEFAULT 'AGENT' CHECK (source IN ('AGENT','MANUAL')),
  agent_id   text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_tot_snap_nozzle_time
  ON fuel_totalizer_snapshots (nozzle_id, taken_at DESC);

-- ---------------------------------------------------------------- รายการขายจากหัวจ่าย
CREATE TABLE IF NOT EXISTS fuel_pump_transactions (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_ref     text UNIQUE NOT NULL,         -- hash(หัวจ่าย|วันที่|seq|totalizer ปลาย)
  ticket_ref     uuid,                         -- uuid ที่ PWA สร้างตอนสั่งจ่าย
  nozzle_id      bigint NOT NULL REFERENCES fuel_nozzles(id),
  pump_seq       integer,
  started_at     timestamptz,
  ended_at       timestamptz NOT NULL,
  liters         numeric NOT NULL CHECK (liters >= 0),
  unit_price     numeric NOT NULL,
  amount         numeric NOT NULL,
  tot_start      numeric,
  tot_end        numeric,
  warning        text,                         -- เช่น ลิตรไม่ตรงส่วนต่าง totalizer
  shift_id       bigint,
  sales_order_id bigint,                       -- ผูกกับบิลเมื่อเก็บเงินแล้ว
  status         text NOT NULL DEFAULT 'UNPAID'
    CHECK (status IN ('UNPAID','PAID','VOID')),
  created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_pump_tx_unpaid
  ON fuel_pump_transactions (nozzle_id, ended_at DESC) WHERE status = 'UNPAID';
CREATE INDEX IF NOT EXISTS idx_pump_tx_ticket
  ON fuel_pump_transactions (ticket_ref) WHERE ticket_ref IS NOT NULL;

-- ---------------------------------------------------------------- คิวคำสั่งจาก PWA
CREATE TABLE IF NOT EXISTS pump_commands (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_ref   uuid NOT NULL DEFAULT gen_random_uuid(),
  nozzle_id    bigint NOT NULL REFERENCES fuel_nozzles(id),
  kind         text NOT NULL CHECK (kind IN
                 ('AUTHORIZE_AMOUNT','AUTHORIZE_VOLUME','AUTHORIZE_FREE','STOP','SET_PRICE')),
  payload      jsonb NOT NULL DEFAULT '{}'::jsonb,
  status       text NOT NULL DEFAULT 'QUEUED'
    CHECK (status IN ('QUEUED','CLAIMED','DONE','ERROR','EXPIRED')),
  requested_by text,
  claimed_by   text,
  claimed_at   timestamptz,
  finished_at  timestamptz,
  expires_at   timestamptz NOT NULL DEFAULT now() + interval '60 seconds',
  error        text,
  created_at   timestamptz NOT NULL DEFAULT now()
);

-- 🔒 กันสั่งซ้อน: หัวจ่ายหนึ่งมีคำสั่งที่ยังไม่จบได้แค่คำสั่งเดียว
--    (บังคับที่ระดับฐานข้อมูล ไม่ใช่แค่ใน agent — กันกรณีสองเครื่องกดพร้อมกัน)
CREATE UNIQUE INDEX IF NOT EXISTS pump_commands_one_active_per_nozzle
  ON pump_commands (nozzle_id) WHERE status IN ('QUEUED','CLAIMED');

-- ---------------------------------------------------------------- ตัวแทน
CREATE TABLE IF NOT EXISTS pump_agents (
  agent_id     text PRIMARY KEY,
  agent_name   text,
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  bus_stats    jsonb NOT NULL DEFAULT '{}'::jsonb,
  nozzles      jsonb NOT NULL DEFAULT '[]'::jsonb
);

