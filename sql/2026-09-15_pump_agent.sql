CREATE OR REPLACE FUNCTION pump_agent_heartbeat(
  p_agent_id text, p_agent_name text DEFAULT NULL,
  p_nozzles jsonb DEFAULT '[]'::jsonb, p_bus_stats jsonb DEFAULT '{}'::jsonb)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'ต้องล็อกอินก่อน'; END IF;
  IF current_staff_role() NOT IN ('AGENT','OWNER') THEN
    RAISE EXCEPTION 'สิทธิ์ไม่พอ: เฉพาะบัญชีตัวแทน (AGENT) หรือเจ้าของร้าน';
  END IF;
  INSERT INTO pump_agents (agent_id, agent_name, last_seen_at, bus_stats, nozzles)
  VALUES (p_agent_id, p_agent_name, now(), p_bus_stats, p_nozzles)
  ON CONFLICT (agent_id) DO UPDATE
    SET agent_name = COALESCE(EXCLUDED.agent_name, pump_agents.agent_name),
        last_seen_at = now(), bus_stats = EXCLUDED.bus_stats, nozzles = EXCLUDED.nozzles;
END; $$;

-- ตัวแทนดึงคำสั่ง: หมดอายุแล้วปิดทิ้งเลย ไม่ส่งออกไปให้ยิงเข้าตู้จ่าย
CREATE OR REPLACE FUNCTION claim_pump_commands(p_agent_id text)
RETURNS TABLE (id bigint, kind text, nozzle_code text, payload jsonb,
               ticket_ref uuid, expires_at timestamptz)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'ต้องล็อกอินก่อน'; END IF;
  IF current_staff_role() NOT IN ('AGENT','OWNER') THEN
    RAISE EXCEPTION 'สิทธิ์ไม่พอ: เฉพาะบัญชีตัวแทน (AGENT) หรือเจ้าของร้าน';
  END IF;

  UPDATE pump_commands c SET status = 'EXPIRED', finished_at = now(),
         error = 'หมดอายุก่อนตัวแทนมารับ'
  WHERE c.status = 'QUEUED' AND c.expires_at < now();

  RETURN QUERY
  UPDATE pump_commands c
     SET status = 'CLAIMED', claimed_by = p_agent_id, claimed_at = now()
   WHERE c.id IN (SELECT c2.id FROM pump_commands c2
                   WHERE c2.status = 'QUEUED' AND c2.expires_at >= now()
                   ORDER BY c2.id FOR UPDATE SKIP LOCKED)
  RETURNING c.id, c.kind,
            (SELECT n.code FROM fuel_nozzles n WHERE n.id = c.nozzle_id),
            c.payload, c.ticket_ref, c.expires_at;
END; $$;

CREATE OR REPLACE FUNCTION finish_pump_command(
  p_command_id bigint, p_status text, p_error text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'ต้องล็อกอินก่อน'; END IF;
  IF current_staff_role() NOT IN ('AGENT','OWNER') THEN
    RAISE EXCEPTION 'สิทธิ์ไม่พอ';
  END IF;
  IF p_status NOT IN ('DONE','ERROR') THEN RAISE EXCEPTION 'สถานะไม่ถูกต้อง: %', p_status; END IF;
  UPDATE pump_commands SET status = p_status, error = p_error, finished_at = now()
   WHERE id = p_command_id;
END; $$;

CREATE OR REPLACE FUNCTION push_nozzle_live(p_row jsonb)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_id bigint;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'ต้องล็อกอินก่อน'; END IF;
  IF current_staff_role() NOT IN ('AGENT','OWNER') THEN RAISE EXCEPTION 'สิทธิ์ไม่พอ'; END IF;
  SELECT id INTO v_id FROM fuel_nozzles WHERE code = p_row->>'nozzle_code';
  IF v_id IS NULL THEN RAISE EXCEPTION 'ไม่รู้จักหัวจ่าย %', p_row->>'nozzle_code'; END IF;
  INSERT INTO fuel_nozzle_live (nozzle_id, state, online, liters, amount, unit_price, ticket_ref, updated_at)
  VALUES (v_id, p_row->>'state', (p_row->>'online')::boolean,
          (p_row->>'liters')::numeric, (p_row->>'amount')::numeric,
          (p_row->>'unit_price')::numeric, NULLIF(p_row->>'ticket_ref','')::uuid, now())
  ON CONFLICT (nozzle_id) DO UPDATE
    SET state = EXCLUDED.state, online = EXCLUDED.online, liters = EXCLUDED.liters,
        amount = EXCLUDED.amount, unit_price = EXCLUDED.unit_price,
        ticket_ref = EXCLUDED.ticket_ref, updated_at = now();
END; $$;

CREATE OR REPLACE FUNCTION push_totalizer_snapshots(p_rows jsonb)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_count integer;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'ต้องล็อกอินก่อน'; END IF;
  IF current_staff_role() NOT IN ('AGENT','OWNER') THEN RAISE EXCEPTION 'สิทธิ์ไม่พอ'; END IF;
  WITH ins AS (
    INSERT INTO fuel_totalizer_snapshots (client_ref, nozzle_id, taken_at, vol_total, amt_total, source, agent_id)
    SELECT r->>'client_ref', n.id, (r->>'taken_at')::timestamptz,
           (r->>'vol_total')::numeric, NULLIF(r->>'amt_total','')::numeric,
           'AGENT', r->>'agent_id'
      FROM jsonb_array_elements(p_rows) r
      JOIN fuel_nozzles n ON n.code = r->>'nozzle_code'
    ON CONFLICT (client_ref) DO NOTHING                 -- ส่งซ้ำกี่ครั้งก็ไม่เกิดแถวซ้ำ
    RETURNING 1)
  SELECT count(*) INTO v_count FROM ins;
  RETURN v_count;
END; $$;

CREATE OR REPLACE FUNCTION push_pump_transactions(p_rows jsonb)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_count integer;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'ต้องล็อกอินก่อน'; END IF;
  IF current_staff_role() NOT IN ('AGENT','OWNER') THEN RAISE EXCEPTION 'สิทธิ์ไม่พอ'; END IF;
  WITH ins AS (
    INSERT INTO fuel_pump_transactions (client_ref, ticket_ref, nozzle_id, pump_seq,
           started_at, ended_at, liters, unit_price, amount, tot_start, tot_end, warning)
    SELECT r->>'client_ref', NULLIF(r->>'ticket_ref','')::uuid, n.id,
           NULLIF(r->>'pump_seq','')::integer,
           NULLIF(r->>'started_at','')::timestamptz, (r->>'ended_at')::timestamptz,
           (r->>'liters')::numeric, (r->>'unit_price')::numeric, (r->>'amount')::numeric,
           NULLIF(r->>'tot_start','')::numeric, NULLIF(r->>'tot_end','')::numeric,
           r->>'warning'
      FROM jsonb_array_elements(p_rows) r
      JOIN fuel_nozzles n ON n.code = r->>'nozzle_code'
    ON CONFLICT (client_ref) DO NOTHING
    RETURNING 1)
  SELECT count(*) INTO v_count FROM ins;
  RETURN v_count;
END; $$;

